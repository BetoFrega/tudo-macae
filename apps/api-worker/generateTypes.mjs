import ts from "typescript";
import { execFileSync } from "node:child_process";
import { readFile, writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
const configuration = ts.parseConfigFileTextToJson("wrangler.jsonc", await readFile("apps/api-worker/wrangler.jsonc", "utf8")).config;
// deploy.mjs flattens the root bindings and selects environment variables explicitly.
delete configuration.env;
configuration.main = resolve("apps/api-worker/index.ts");
const directory = await mkdtemp(join(tmpdir(), "api-worker-types-"));
try {
  const path = join(directory, "wrangler.jsonc");
  await writeFile(path, JSON.stringify(configuration));
  execFileSync("wrangler", ["types", "--config", path, "--include-runtime=false", "--strict-vars=false", join(directory, "env.d.ts")], { stdio: "pipe", env: { ...process.env, WRANGLER_LOG_PATH: join(directory, "wrangler.log") } });
  const output = (await readFile(join(directory, "env.d.ts"), "utf8")).replace(/mainModule: typeof import\("[^"]+"\)/, "mainModule: typeof import(\"./index\")");
  await writeFile("apps/api-worker/env.d.ts", output.replace(/\/\/ Generated by Wrangler[^\n]*/, "// Generated by `mise exec -- node apps/api-worker/generateTypes.mjs` from the flattened deployment configuration."));
}
finally { await rm(directory, { recursive: true, force: true }); }
