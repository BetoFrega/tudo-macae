export interface DemoAccount {
  uid: string;
  email: string;
  claims: Record<string, unknown>;
}

/** The README's promises: every demo account is `<nome>@demo.local`, every public-information source sits under this URL. */
const DEMO_EMAIL_DOMAIN = "@demo.local";
const DEMO_SOURCE_PREFIX = "https://example.com/negocios/";

export { fixture };

const sessions = new Map<string, Promise<string>>();

/**
 * One sign-in per account for the whole file: Better Auth allows three per
 * account every ten seconds, and the seed signs in the same accounts.
 */
export function sessionFor(email: string, password = DEMO_PASSWORD) {
  let session = sessions.get(email);
  if (!session) {
    session = signInWorkerAccount({ email, password });
    sessions.set(email, session);
  }
  return session;
}

export async function classifiedsFor(email: string, password = DEMO_PASSWORD) {
  const client = createClassifiedsClient({
    origin: process.env.AUTHENTICATION_API_URL!,
    publicOrigin: process.env.PUBLIC_APP_ORIGIN!,
    allowLocal: true,
  });
  const credential = { session: await sessionFor(email, password) };
  return {
    read: <T>(operation: ClassifiedsReadOperation, input: unknown) => client.read<T>(operation, input, credential),
    write: <T>(operation: ClassifiedsWriteOperation, input: unknown) => client.write<T>(operation, input, credential),
  };
}

export function asAdmin() {
  return classifiedsFor("admin@demo.local");
}

export async function findAccount(email: string) {
  return fixture<DemoAccount | null>("/find", { email });
}

/** Every demo account owns a profile, so the owners of the seeded profiles are the seeded accounts. */
export async function seededUsers() {
  const ownerIds = new Set((await allProfiles()).flatMap(profile => profile.userId ? [profile.userId] : []));
  const owners = await Promise.all([...ownerIds].map(uid => fixture<DemoAccount | null>("/find", { uid })));
  return owners.filter(owner => owner?.email.endsWith(DEMO_EMAIL_DOMAIN)) as DemoAccount[];
}

export async function categoryCatalog() {
  return (await asAdmin()).read<CategoryWithSubcategories[]>("categories.catalog", null);
}

async function allProfiles() {
  return (await asAdmin()).read<AdvertiserProfileData[]>("profiles.all", null);
}

/**
 * Profile ids are generated by the Worker, so the seed's profiles are found by
 * their demo owner or demo source. The fixture is shared across the run, and
 * every assertion is about what the seed owns, never about how many records
 * happen to exist.
 */
export async function seededProfiles() {
  const [profiles, users] = await Promise.all([allProfiles(), seededUsers()]);
  const demoOwners = new Set(users.map(user => user.uid));
  return profiles.filter(profile => profile.userId
    ? demoOwners.has(profile.userId)
    : profile.source?.url.startsWith(DEMO_SOURCE_PREFIX));
}

export function profileTitled(profiles: AdvertiserProfileData[], title: string) {
  const profile = profiles.find(candidate => candidate.title === title);
  if (!profile) throw new Error(`No seeded profile is titled "${title}".`);
  return profile;
}

export async function seededAds() {
  const ads = await (await asAdmin()).read<AdData[]>("ads.all", null);
  return ads.filter(ad => ad.id.startsWith(DEMO_PREFIX));
}

/** Stands in for an advertiser who used the site by hand between two restarts. */
async function createHandMadeRecords() {
  const email = `hand-made-${crypto.randomUUID()}@example.test`;
  const { uid } = await fixture<{ uid: string }>("/create", { email, password: DEMO_PASSWORD, emailVerified: true });
  const owner = await classifiedsFor(email);
  const [category] = (await categoryCatalog()).filter(candidate => candidate.isActive && candidate.subcategories.length > 0);
  const area = { categoryId: category!.id, subcategoryId: category!.subcategories[0]!.id };
  const profileId = await owner.write<string>("profiles.create", {
    title: "Feito à mão",
    description: "",
    contacts: [{ number: "22999990000", isWhatsapp: true }],
    activityAreas: [area],
    operationId: crypto.randomUUID(),
  });
  const adId = `hand-made-${crypto.randomUUID()}`;
  await owner.write("ads.create", {
    id: adId,
    ...area,
    advertiserProfileId: profileId,
    title: "Feito à mão",
    text: "Anúncio criado fora do seed.",
  });
  return { uid, profileId, adId };
}

export function registerDemoSeedFixture() {
  beforeAll(async () => {
    vi.stubEnv("NEXT_RUNTIME", "nodejs");
    vi.stubEnv("NODE_ENV", "development");

    demo.bootTime = Date.now();
    demo.firstRun = await seedDemoData();

    demo.handMade = await createHandMadeRecords();

    const suffix = crypto.randomUUID();
    const unrelatedCategory = await (await asAdmin()).write<{ record: { id: string } }>("categories.create", {
      name: "Categoria externa de teste",
      slug: `categoria-externa-${suffix}`,
      isActive: true,
      idempotencyKey: suffix,
    });
    demo.unrelatedCategoryId = unrelatedCategory.record.id;

    demo.secondRun = await seedDemoData();
  }, 120_000);

  afterAll(async () => {
    vi.unstubAllEnvs();
    if (demo.unrelatedCategoryId) await fixture("/delete-category", { id: demo.unrelatedCategoryId });

    // Owned ads and profiles go with their account; claimable profiles have none.
    const claimable = (await seededProfiles()).filter(profile => !profile.userId);
    await Promise.all(claimable.map(profile => fixture("/delete-profile", { id: profile.id })));
    const users = [...await seededUsers(), ...(demo.handMade ? [{ uid: demo.handMade.uid }] : [])];
    await Promise.all(users.map(user => fixture("/delete", { uid: user.uid })));
    sessions.clear();
  });
}
