import sharp from "sharp";
import type { AdData } from "@tudomacae/ads/types";
import type { AdvertiserProfileData } from "@tudomacae/advertiser-identity/model";
import { encodeWithinPhotoLimit } from "@/integrations/ads/use-cases/sanitizeAdPhoto";
import type { DemoImageSource } from "../image-source";
import { accountEmail, DEMO_PASSWORD } from "./accounts";
import { businessKeyForAd } from "./ads";
import { ownedBusiness } from "./businesses";
import type { CuratedDemoImage } from "./data/images";
import { demoIdFor } from "./demoKey";
import { classifiedsAs, signIn, type DemoClassifieds } from "./worker";

interface PhotoTarget {
  owner: DemoClassifieds;
  ownerKind: "ad" | "profile";
  ownerId: string;
  revision: number;
  hasPhoto: boolean;
}

async function photoTarget(image: CuratedDemoImage): Promise<PhotoTarget> {
  const target = image.target;
  const businessKey = target.kind === "ad" ? businessKeyForAd(target.adKey) : target.businessKey;
  const business = ownedBusiness(businessKey);
  const owner = await classifiedsAs(await signIn(accountEmail(business.accountKey), DEMO_PASSWORD));

  if (target.kind === "ad") {
    const id = demoIdFor(target.adKey);
    const ad = await owner.read<AdData | null>("ads.owned", { id });
    if (!ad?.revision) throw new Error(`Demo image "${image.key}" names missing ad target "${id}".`);
    return { owner, ownerKind: "ad", ownerId: id, revision: ad.revision, hasPhoto: ad.images.length > 0 };
  }

  // Profile ids are generated by the Worker, so the business is found among
  // its owner's own profiles by the title the data file gave it.
  const profile = (await owner.read<AdvertiserProfileData[]>("profiles.mine", null))
    .find(candidate => candidate.title === business.title);
  if (!profile) throw new Error(`Demo image "${image.key}" names missing business target "${businessKey}".`);
  return { owner, ownerKind: "profile", ownerId: profile.id, revision: profile.revision ?? 1, hasPhoto: Boolean(profile.photoPath) };
}

/**
 * Gives one ad or business its curated photo through the Worker's photo upload,
 * signed in as the owner — the same path the photo picker uses.
 *
 * A target that already has a photo is left alone, so a later boot against the
 * same fixture resumes instead of stacking copies. The download is re-encoded
 * to fit the Classifieds photo limit before it is sent.
 */
export async function seedClassifiedsImage(
  image: CuratedDemoImage,
  imageSource: DemoImageSource,
): Promise<"complete" | "ready"> {
  const target = await photoTarget(image);
  if (target.hasPhoto) return "complete";

  const downloaded = await imageSource.download(image);
  const bytes = await encodeWithinPhotoLimit(sharp(downloaded.bytes, { pages: 1, failOn: "error" }));
  await target.owner.uploadPhoto({
    ownerKind: target.ownerKind,
    ownerId: target.ownerId,
    operationId: crypto.randomUUID(),
    expectedRevision: target.revision,
    mimeType: "image/webp",
    bytes: new Uint8Array(bytes),
    ...(image.target.kind === "ad" ? { title: image.target.title, description: image.target.description } : {}),
  });
  return "ready";
}
